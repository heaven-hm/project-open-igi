// Status/limits: STRUCTURALLY_VERIFIED; high for assignment and stride; Binary Ninja's autogenerated name is not semantically consistent.
void Qvm_SetOpcodeHandler(std::int32_t opcode, std::int32_t variant, QvmOpcodeHandler handler)
{
    QvmOpcodeHandlerTable[opcode].handlers[static_cast<std::size_t>(variant)] = handler;
}

