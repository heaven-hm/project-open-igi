QvmOpcodeHandlerRecord QvmOpcodeHandlerTable[qvm_opcode_handler_count]{};

// The handler table stores 32-bit function pointers in the retail 32-bit ABI; on a 64-bit host
// the pointer width differs, so the size checks only apply to the i386 target.
#if defined(_M_IX86) || defined(__i386__)
static_assert(sizeof(QvmOpcodeHandler) == 4U);
static_assert(sizeof(QvmOpcodeHandlerRecord) == 0x18U);
#endif

// Native: Qvm_PushInteger() - retail VA 0x004BDA00; Binary Ninja label Sys_PushStack_29.
// Behavior: stores tag 1 at type_stack[--type_stack_index] and the supplied DWORD at value_stack[--value_stack_index].
// Evidence: REA/Ghidra ev_fc8c4a96e5363fb9ba98aad334c2607004b6ee4cd58f1894cf78e5d43a93a525; bytes verified against IGI.EXE.
// CFG: radare2 1 block/0 edges; Binary Ninja 1 block; source CFG agreement 100% (not C++ semantic accuracy).
// Confidence: high for this leaf's writes; caller state allocation and complete VM integration are not ported.
// Signature: x86 cdecl with two 32-bit stack arguments; current declaration retains the observed argument order.
// Usage/tests: opcode handlers call this native; unit test checks both index decrements and both stack writes.
void Qvm_PushInteger(QvmNativeStatePrefix* state, std::uint32_t value)
{
    const std::int32_t next_type_stack_index = state->type_stack_index - 1;
    const std::int32_t next_value_stack_index = state->value_stack_index - 1;

    state->value_stack_index = next_value_stack_index;
    state->type_stack_index = next_type_stack_index;
    state->type_stack[next_type_stack_index] = 1U;
    state->value_stack[next_value_stack_index] = value;
}

// Native: Qvm_SetOpcodeHandler() - retail VA 0x004BD3D0; Binary Ninja label Sys_AllocateMemory_29.
// Behavior: writes the callback to variant + opcode * 6 DWORDs in the retail 24-byte opcode record.
// Evidence: REA/Ghidra ev_5cda7406ec531b3d34c1241bac86c40d46966b0ae4b27c81dfbd92c510cb8dcf; Radare2 confirms cdecl stores.
// CFG: radare2 1 block/0 edges; Binary Ninja 1 block; source CFG agreement 100% (not C++ semantic accuracy).
// Confidence: high for assignment and stride; Binary Ninja's autogenerated name is not semantically consistent.
// Signature: preserves the three observed argument positions; callback storage is relocated into owned x86 process memory.
// Usage/tests: QVM initializer calls this registration native; unit tests verify opcode and variant slot selection.
void Qvm_SetOpcodeHandler(std::int32_t opcode, std::int32_t variant, QvmOpcodeHandler handler)
{
    QvmOpcodeHandlerTable[opcode].handlers[static_cast<std::size_t>(variant)] = handler;
}

// Native: Qvm_ExecuteInstructions() - retail VA 0x004BCFD0; Binary Ninja label Sys_ExecuteBytecode_28.
// Behavior: clears the stop flag, exits on nonzero +0x20 status, dispatches opcode variant zero, and loops while +0x2C is zero.
// Evidence: REA/Ghidra ev_7b5b04f8089dae45a2e6a5b52cdcec6c771948bcf7b02c21d635a76164439de4; Radare2 confirms all branches.
// CFG: radare2 4 blocks/5 edges; Binary Ninja 4 blocks; source CFG agreement 100% (not C++ semantic accuracy).
// Confidence: high for offsets and callback argument values; QVM table initialization and opcode closure are incomplete.
// Signature: x86 cdecl state pointer; callback receives (state, 0, opcode, 0), and caller removes 16 stack bytes.
// Usage/tests: Qvm_ExecuteInstructions drives registered handlers; tests cover sequential dispatch, stop and status paths.
void Qvm_ExecuteInstructions(QvmNativeStatePrefix* state)
{
    state->stop_flag = 0U;

    do {
        if (state->error_status != 0U) {
            return;
        }

        const std::uint32_t opcode = std::to_integer<std::uint8_t>(
            state->code_base[state->instruction_offset]);
        QvmOpcodeHandlerTable[opcode].handlers[0U](state, 0U, opcode, 0U);
    } while (state->stop_flag == 0U);
}

