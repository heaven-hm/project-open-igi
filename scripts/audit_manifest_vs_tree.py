#!/usr/bin/env python3
"""Audit manifest records against implementation files that actually exist.

Every manifest row should point at an implementation file. Rows whose path is missing,
or whose address has no file under engine/src/retail/<domain>/native_<addr>.cpp, mean
the record outran the tree: a status that no code backs.

Usage: python3 scripts/audit_manifest_vs_tree.py [--write-report]
"""
from __future__ import annotations

import argparse
import json
import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--write-report", action="store_true")
    options = parser.parse_args()

    manifest = json.loads((ROOT / "docs/fidelity/native-verification.json").read_text())
    rows = [row for row in manifest.get("natives", []) if row.get("address")]
    implemented = {int(path.name[7:13], 16) for path in (ROOT / "engine/src/retail").glob("*/native_*.cpp")}

    missing_file = []
    missing_address = []
    for row in rows:
        address = int(row["address"], 16)
        path = (row.get("implementation") or {}).get("path")
        if path and not (ROOT / path).is_file():
            missing_file.append((row, "declared path missing"))
        elif address not in implemented and not path:
            missing_address.append(row)

    no_code = [row for row in rows if int(row["address"], 16) not in implemented]
    backed = len(rows) - len(no_code)

    print(f"manifest rows:              {len(rows)}")
    print(f"implementation files:       {len(implemented)}")
    print(f"rows with a real file:      {backed}")
    print(f"rows with no code at all:   {len(no_code)}")
    print(f"rows whose path is missing: {len(missing_file)}")

    if options.write_report:
        report = ROOT / "docs/fidelity/evidence/manifest-vs-tree-audit.md"
        lines = [
            "# Manifest versus tree audit",
            "",
            "Generated by `scripts/audit_manifest_vs_tree.py`. A manifest row is only meaningful when the implementation file it",
            "names exists and its address has a native file under `engine/src/retail/<domain>/`. Rows without code are statuses",
            "that nothing backs, and they must not be read as coverage.",
            "",
            f"- manifest rows: **{len(rows)}**",
            f"- implementation files: **{len(implemented)}**",
            f"- rows backed by a real file: **{backed}**",
            f"- rows with no code at all: **{len(no_code)}**",
            f"- rows whose declared path does not exist: **{len(missing_file)}**",
            "",
        ]
        if no_code:
            lines.append("## Rows with no implementation file")
            lines.append("")
            lines.append("| native name | retail address | status in record |")
            lines.append("| --- | --- | --- |")
            for row in sorted(no_code, key=lambda item: int(item["address"], 16))[:200]:
                status = (row.get("verification") or {}).get("status", "?")
                name = (row.get("name") or "unnamed").replace("|", "/")
                lines.append(f"| `{name}` | `{row['address']}` | {status} |")
            if len(no_code) > 200:
                lines.append("")
                lines.append(f"Only the first 200 of {len(no_code)} rows are listed.")
            lines.append("")
        report.write_text("\n".join(lines))
        print(f"wrote {report.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
